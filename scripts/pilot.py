"""Pilot: do agent-authored Terraform PRs introduce more Checkov failures than human PRs in the same repos?

For each PR: fetch every changed .tf file at the base and head commits, run Checkov on
both versions, and count failed checks present in head but not in base ("introduced").

Usage:  .venv/bin/python scripts/pilot.py --agent-prs 20
Needs:  `gh` logged in. Output: data/pilot_results.csv, data/pilot_findings.csv
Limit:  files are scanned one PR at a time without module context (pilot only).
"""
import argparse, base64, csv, json, os, re, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = sys.executable

AGENT_QUERIES = [  # disclosed agent traces in PR bodies
    '"Generated with Claude Code"',
    '"Co-Authored-By: Claude"',
    '"Generated with Codex"',
]
AGENT_AUTHORS = {"Copilot", "copilot-swe-agent[bot]", "devin-ai-integration[bot]", "chatgpt-codex-connector[bot]", "cursor[bot]"}
AGENT_RE = re.compile(r"(claude code|co-authored-by: claude|codex|copilot|devin|cursor agent|generated by ai|🤖)", re.I)
BOT_RE = re.compile(r"(\[bot\]|dependabot|renovate)", re.I)


def gh(*args, raw=False):
    out = subprocess.run(["gh", *args], capture_output=True, text=True)
    if out.returncode != 0:
        return None
    return out.stdout if raw else json.loads(out.stdout or "null")


def find_agent_prs(limit):
    seen, prs = set(), []
    for q in AGENT_QUERIES:
        res = gh("search", "prs", q, "--language=HCL", "--merged", "--limit", str(limit),
                 "--json", "repository,number,title,url,author") or []
        for r in res:
            key = (r["repository"]["nameWithOwner"], r["number"])
            if key not in seen:
                seen.add(key); prs.append({"repo": key[0], "number": key[1], "group": "agent", "url": r["url"]})
        if len(prs) >= limit:
            break
    return prs[:limit]


def pr_meta(repo, number):
    return gh("api", f"repos/{repo}/pulls/{number}")


def pr_tf_files(repo, number):
    files = gh("api", f"repos/{repo}/pulls/{number}/files?per_page=100") or []
    return [f for f in files if f["filename"].endswith(".tf")]


def is_agent_or_bot(repo, number, meta):
    login = (meta.get("user") or {}).get("login", "")
    if login in AGENT_AUTHORS or BOT_RE.search(login):
        return True
    if AGENT_RE.search(meta.get("body") or ""):
        return True
    commits = gh("api", f"repos/{repo}/pulls/{number}/commits?per_page=100") or []
    return any(AGENT_RE.search(c["commit"]["message"]) for c in commits)


def human_prs_in_repo(repo, want):
    """Merged PRs in the same repo that touch .tf files and show no agent/bot traces."""
    out = []
    pulls = gh("api", f"repos/{repo}/pulls?state=closed&per_page=50") or []
    for p in pulls:
        if not p.get("merged_at") or len(out) >= want:
            continue
        if is_agent_or_bot(repo, p["number"], p):
            continue
        if pr_tf_files(repo, p["number"]):
            out.append({"repo": repo, "number": p["number"], "group": "human", "url": p["html_url"]})
    return out


def file_at(repo, path, sha):
    data = gh("api", f"repos/{repo}/contents/{path}?ref={sha}")
    if not data or data.get("encoding") != "base64":
        return None
    return base64.b64decode(data["content"]).decode("utf-8", "replace")


def checkov_fails(directory):
    if not any(Path(directory).rglob("*.tf")):
        return set()
    out = subprocess.run([PY, "-m", "checkov.main", "-d", directory, "--framework", "terraform",
                          "-o", "json", "--quiet", "--compact", "--skip-download"],
                         capture_output=True, text=True)
    try:
        data = json.loads(out.stdout)
    except json.JSONDecodeError:
        return set()
    reports = data if isinstance(data, list) else [data]
    fails = set()
    for rep in reports:
        for f in rep.get("results", {}).get("failed_checks", []):
            fails.add((f["check_id"], f.get("resource", ""), Path(f.get("file_path", "")).name))
    return fails


def analyse(pr):
    meta = pr_meta(pr["repo"], pr["number"])
    if not meta:
        return None
    files = pr_tf_files(pr["repo"], pr["number"])
    base, head = meta["base"]["sha"], meta["head"]["sha"]
    with tempfile.TemporaryDirectory() as b, tempfile.TemporaryDirectory() as h:
        for f in files:
            name = f["filename"].replace("/", "__")
            if f["status"] != "added":
                src = file_at(pr["repo"], f.get("previous_filename") or f["filename"], base)
                if src: Path(b, name).write_text(src)
            if f["status"] != "removed":
                src = file_at(pr["repo"], f["filename"], head)
                if src: Path(h, name).write_text(src)
        before, after = checkov_fails(b), checkov_fails(h)
    introduced = sorted(after - before)
    return {**pr, "tf_files": len(files), "additions": meta.get("additions", 0),
            "deletions": meta.get("deletions", 0), "fails_before": len(before),
            "fails_after": len(after), "introduced": len(introduced),
            "fixed": len(before - after), "introduced_checks": introduced}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--agent-prs", type=int, default=20)
    ap.add_argument("--humans-per-repo", type=int, default=2)
    a = ap.parse_args()

    agent = [p for p in find_agent_prs(a.agent_prs) if pr_tf_files(p["repo"], p["number"])]
    print(f"agent PRs touching .tf: {len(agent)}", flush=True)
    humans = []
    for repo in sorted({p["repo"] for p in agent}):
        humans += human_prs_in_repo(repo, a.humans_per_repo)
    print(f"matched human PRs: {len(humans)}", flush=True)

    rows, findings = [], []
    for pr in agent + humans:
        r = analyse(pr)
        if r is None:
            continue
        print(f'{r["group"]:5} {r["repo"]}#{r["number"]}: +{r["introduced"]} introduced, -{r["fixed"]} fixed', flush=True)
        for cid, res, fname in r.pop("introduced_checks"):
            findings.append({"group": r["group"], "repo": r["repo"], "number": r["number"],
                             "check_id": cid, "resource": res, "file": fname})
        rows.append(r)

    (ROOT / "data").mkdir(exist_ok=True)
    with open(ROOT / "data/pilot_results.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    with open(ROOT / "data/pilot_findings.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["group", "repo", "number", "check_id", "resource", "file"])
        w.writeheader(); w.writerows(findings)

    for g in ("agent", "human"):
        sub = [r for r in rows if r["group"] == g]
        if sub:
            share = sum(r["introduced"] > 0 for r in sub) / len(sub)
            print(f"{g}: {len(sub)} PRs, {share:.0%} introduced ≥1 failed check, "
                  f"{sum(r['introduced'] for r in sub)} introduced in total")


if __name__ == "__main__":
    main()
